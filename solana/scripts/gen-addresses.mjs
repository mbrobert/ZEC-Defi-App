// Generates programs/oilskin/src/generated/addresses.rs from @zyo/shared's solana.ts — the second seam.
// The program never types a program id, market, reserve, vault or mint of its own; it consumes these, and
// test/addresses-seam.test.mjs fails the build if the committed file drifts from shared (which is itself
// pinned to docs/VERIFIED-SOLANA-FACTS.md).
//
//   node solana/scripts/gen-addresses.mjs            → writes the file
//   node solana/scripts/gen-addresses.mjs --check    → exit 1 if the committed file differs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { CCTP_DOMAINS, CCTP_V2_SOLANA, KAMINO_ZCASH_MARKET, SOLANA_PROGRAMS, SOLANA_TOKENS, KLEND_SEEDS } from "@zyo/shared";

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "programs", "oilskin", "src", "generated", "addresses.rs");

const B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
const assertKey = (s) => {
  if (!/^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(s)) throw new Error(`not base58: ${s}`);
  let n = 0n;
  for (const ch of s) n = n * 58n + BigInt(B58.indexOf(ch));
  const lead = s.match(/^1*/)[0].length;
  const bytes = lead + (n === 0n ? 0 : Math.ceil(n.toString(16).length / 2));
  if (bytes !== 32) throw new Error(`not 32 bytes: ${s}`);
  return s;
};

const L = [];
L.push("// GENERATED by solana/scripts/gen-addresses.mjs from @zyo/shared (packages/shared/src/solana.ts) — DO NOT EDIT.");
L.push("// Every address here was read from Solana mainnet on 2026-09-12 and is recorded in docs/VERIFIED-SOLANA-FACTS.md;");
L.push("// solana/test/addresses-seam.test.mjs pins this file to shared, and shared's tests pin it to the facts file.");
L.push("#![allow(dead_code)]");
L.push("use anchor_lang::prelude::{pubkey, Pubkey};");
L.push("");
const c = (name, doc, key) => { L.push(`/// ${doc}`); L.push(`pub const ${name}: Pubkey = pubkey!("${assertKey(key)}");`); };
c("KLEND_PROGRAM", "Kamino Lend.", SOLANA_PROGRAMS.klend);
c("SCOPE_PROGRAM", "Scope — Kamino's oracle aggregator.", SOLANA_PROGRAMS.scope);
c("FARMS_PROGRAM", "Kamino Farms (in every klend V2 CPI account list even when a reserve has no farm).", SOLANA_PROGRAMS.farms);
c("SPL_TOKEN_PROGRAM", "SPL Token (ZEC and USDC are both classic SPL Token mints).", SOLANA_PROGRAMS.splToken);
c("ASSOCIATED_TOKEN_PROGRAM", "Associated Token Account program.", SOLANA_PROGRAMS.associatedToken);
L.push("");
c("ZCASH_LENDING_MARKET", "Kamino's ZCASH market (LendingMarket).", KAMINO_ZCASH_MARKET.lendingMarket);
c("SCOPE_ORACLE_PRICES", "The Scope OraclePrices account both reserves read (klend feed, NOT the Hubble feed).", KAMINO_ZCASH_MARKET.scopeOraclePrices);
L.push("");
const r = KAMINO_ZCASH_MARKET.reserves;
c("ZEC_MINT", "Bridged ZEC mint (8 decimals; no freeze authority).", SOLANA_TOKENS.ZEC.mint);
c("ZEC_RESERVE", "ZEC reserve (collateral only; LTV/LT read live from it, never typed).", r.ZEC.address);
c("ZEC_LIQUIDITY_SUPPLY", "ZEC reserve liquidity supply vault.", r.ZEC.liquiditySupplyVault);
c("ZEC_FEE_VAULT", "ZEC reserve fee vault.", r.ZEC.liquidityFeeVault);
c("ZEC_COLLATERAL_MINT", "ZEC reserve cToken mint.", r.ZEC.collateralMint);
c("ZEC_COLLATERAL_SUPPLY", "ZEC reserve cToken supply vault (deposit destination / withdraw source).", r.ZEC.collateralSupplyVault);
L.push("");
c("USDC_MINT", "USDC mint (6 decimals; Circle holds a freeze authority).", SOLANA_TOKENS.USDC.mint);
c("USDC_RESERVE", "USDC reserve (the debt side).", r.USDC.address);
c("USDC_LIQUIDITY_SUPPLY", "USDC reserve liquidity supply vault (borrow source / repay destination).", r.USDC.liquiditySupplyVault);
c("USDC_FEE_VAULT", "USDC reserve fee vault (borrow fee receiver).", r.USDC.liquidityFeeVault);
L.push("");
L.push(`/// Scope price-chain index the ZEC reserve points at (re-read from the reserve and asserted).`);
L.push(`pub const ZEC_SCOPE_PRICE_INDEX: u16 = ${r.ZEC.scopePriceChain[0]};`);
L.push(`pub const USDC_SCOPE_PRICE_INDEX: u16 = ${r.USDC.scopePriceChain[0]};`);
L.push(`pub const ZEC_DECIMALS: u8 = ${SOLANA_TOKENS.ZEC.decimals};`);
L.push(`pub const USDC_DECIMALS: u8 = ${SOLANA_TOKENS.USDC.decimals};`);
L.push("");
L.push("/// klend PDA seed strings (klend-sdk 12.0.0 `utils/seeds.js`).");
L.push(`pub const KLEND_SEED_LENDING_MARKET_AUTHORITY: &[u8] = b"${KLEND_SEEDS.lendingMarketAuthority}";`);
L.push(`pub const KLEND_SEED_USER_METADATA: &[u8] = b"${KLEND_SEEDS.userMetadata}";`);
L.push("");
L.push("// Circle's CCTP V2 — the USDC rail to the user's Base account (docs/VERIFIED-SOLANA-FACTS.md Addenda 1 and 3;");
L.push("// packages/shared/src/cctp.ts). PDAs derived with Circle's seeds and read live 2026-09-13; the program passes");
L.push("// them by address so a wrong one cannot be handed to `deposit_for_burn`.");
c("CCTP_TOKEN_MESSENGER_MINTER_V2", "TokenMessengerMinterV2 program.", CCTP_V2_SOLANA.programs.tokenMessengerMinterV2);
c("CCTP_MESSAGE_TRANSMITTER_V2", "MessageTransmitterV2 program.", CCTP_V2_SOLANA.programs.messageTransmitterV2);
c("CCTP_TOKEN_MESSENGER", "[\"token_messenger\"] of the messenger program.", CCTP_V2_SOLANA.pdas.tokenMessenger);
c("CCTP_TOKEN_MINTER", "[\"token_minter\"].", CCTP_V2_SOLANA.pdas.tokenMinter);
c("CCTP_SENDER_AUTHORITY", "[\"sender_authority\"] — signs the transmitter CPI; no account exists at it.", CCTP_V2_SOLANA.pdas.senderAuthority);
c("CCTP_LOCAL_TOKEN_USDC", "[\"local_token\", USDC mint] — carries the 10 M USDC per-message burn cap.", CCTP_V2_SOLANA.pdas.localTokenUsdc);
c("CCTP_REMOTE_TOKEN_MESSENGER_BASE", "[\"remote_token_messenger\", \"6\"] — names Base's TokenMessengerV2.", CCTP_V2_SOLANA.pdas.remoteTokenMessengerBase);
c("CCTP_MESSAGE_TRANSMITTER", "[\"message_transmitter\"] of the transmitter program (local domain 5).", CCTP_V2_SOLANA.pdas.messageTransmitter);
L.push(`/// CCTP domain ids (Circle's fee endpoints; Base's transmitter says 6, Solana's 5).`);
L.push(`pub const CCTP_DOMAIN_SOLANA: u32 = ${CCTP_DOMAINS.solana};`);
L.push(`pub const CCTP_DOMAIN_BASE: u32 = ${CCTP_DOMAINS.base};`);
L.push(`/// Seeds the program derives per call: Circle's denylist entry for an owner, and Anchor's event authority.`);
L.push(`pub const CCTP_SEED_DENYLIST: &[u8] = b"${CCTP_V2_SOLANA.seeds.denylistAccount}";`);
L.push(`pub const CCTP_SEED_EVENT_AUTHORITY: &[u8] = b"${CCTP_V2_SOLANA.seeds.eventAuthority}";`);
L.push(`/// Anchor's global instruction discriminator preimage for the burn.`);
L.push(`pub const CCTP_DEPOSIT_FOR_BURN_PREIMAGE: &[u8] = b"${CCTP_V2_SOLANA.depositForBurnDiscriminatorPreimage}";`);
const disc = createHash("sha256").update(CCTP_V2_SOLANA.depositForBurnDiscriminatorPreimage).digest().subarray(0, 8);
L.push(`/// sha256(that preimage)[..8] — Anchor's instruction discriminator, computed here, pinned by the seam test.`);
L.push(`pub const CCTP_DEPOSIT_FOR_BURN_DISCRIMINATOR: [u8; 8] = [${Array.from(disc).join(", ")}];`);
L.push("");
const out = L.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error(`DRIFT: ${target} does not match @zyo/shared — run: node solana/scripts/gen-addresses.mjs`);
    process.exit(1);
  }
  console.log(`addresses seam OK: ${target} matches @zyo/shared`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
